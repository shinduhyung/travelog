"""Write STATUS.md: every inventory entry with its exact state, so a new session
can see which screens are finished in which languages and what is left.

usage: python -I tool/l10n/overflow_audit/status.py
"""
import json, os, sys
from collections import defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.argv = [sys.argv[0]]
import drive  # noqa: E402  (reuses the inventory loader and step resolution)

ALL = [e['code'] for e in json.load(open(os.path.join(drive.REPO, 'build/l10n/languages.json'),
                                         encoding='utf-8'))['languages'] if e['code'] != 'en']

latest = {}
for line in open(drive.RESULTS, encoding='utf-8'):
    r = json.loads(line)
    latest[(r['id'], r.get('tier', 0))] = r

entries, seen = [], set()
for e in drive.load_inventory():
    if e['id'] not in seen:
        seen.add(e['id'])
        entries.append(e)

rows = defaultdict(list)
for e in entries:
    checked, overflow, fails = set(), set(), []
    for tier in (0, 1, 2):
        r = latest.get((e['id'], tier))
        if not r:
            continue
        if r.get('nav_ok'):
            checked |= set(r['langs'])
            overflow |= {o for v in r['langs'].values() for o in v.get('overflow', [])}
        else:
            fails.append(r.get('nav_fail') or '?')
    if e.get('unsafe'):
        state = 'unsafe'
    elif not e.get('path'):
        state = 'no_path'
    elif overflow:
        state = 'overflow'
    elif checked >= set(ALL):
        state = 'done'
    elif checked:
        state = 'partial'
    elif fails:
        state = 'nav_failed'
    elif not all(drive.step_ready(e, st) for st in e['path']):
        state = 'needs_calibration'
    else:
        state = 'not_started'
    missing = [c for c in ALL if c not in checked]
    rows[state].append((e, sorted(checked), missing, sorted(overflow), fails))

ORDER = ['overflow', 'nav_failed', 'needs_calibration', 'partial', 'not_started', 'done', 'unsafe', 'no_path']
NOTE = {
    'overflow': 'Overflow still logged: fix file:line, then `drive.py --only <id>`.',
    'nav_failed': 'Could not reach the screen. Paths were fixed after these ran; run with `--retry`.',
    'needs_calibration': 'A path step has no coordinates yet: add it to calib.json.',
    'partial': 'Reached and checked in some languages only; the rest are listed per entry.',
    'not_started': 'Runnable, never run.',
    'done': f'Checked in all {len(ALL)} languages, no overflow.',
    'unsafe': 'Skipped on purpose (the path would change or delete data).',
    'no_path': 'No navigation path in the inventory.',
}
out = [f'# Audit status (generated by status.py; do not edit)\n',
       f'{len(entries)} unique inventory entries. Languages: {" ".join(ALL)}\n',
       '| state | entries |', '|---|---|']
out += [f'| {s} | {len(rows[s])} |' for s in ORDER]
for s in ORDER:
    out.append(f'\n## {s} ({len(rows[s])})\n\n{NOTE[s]}\n')
    for e, checked, missing, overflow, fails in rows[s]:
        line = f"- `{e['id']}` — {e.get('file', '?')} (risk {e.get('risk', '?')})"
        if s == 'partial':
            line += f"\n  - checked: {' '.join(checked)}\n  - missing: {' '.join(missing)}"
        if overflow:
            line += ''.join(f'\n  - overflow: {o}' for o in overflow)
        if fails and s == 'nav_failed':
            line += f'\n  - last failure: {fails[-1]}'
        out.append(line)
open(os.path.join(HERE, 'STATUS.md'), 'w', encoding='utf-8').write('\n'.join(out) + '\n')
print('\n'.join(out[:12]))

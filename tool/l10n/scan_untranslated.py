"""List UI text in lib/ that will still show in English in another language.

  A  literal tr('...') strings with no translation in the catalog
  B  English literals shown without tr(): Text('...'), title: '...', hintText: '...'
  C  variables shown raw: Text(x.name), Text(item.title) (data names; many are
     intentional entity names, so this list needs a human look)

usage: python -I tool/l10n/scan_untranslated.py [lang]   (default ko)
Writes tool/l10n/untranslated_report.md.
"""
import json, re, sys
from collections import defaultdict
from pathlib import Path

sys.stdout.reconfigure(encoding='utf-8')
ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(Path(__file__).parent))
from build import code_strings  # noqa: E402

lang = sys.argv[1] if len(sys.argv) > 1 else 'ko'
manifest = json.loads((ROOT / 'build/l10n/languages.json').read_text(encoding='utf-8'))
entry = next(e for e in manifest['languages'] if e['code'] == lang)
catalog = json.loads((ROOT / 'build/l10n' / entry['file']).read_text(encoding='utf-8'))
known = {k.strip().lower() for k in list(catalog['messages']) + list(catalog['countries'])}

STR = r"""('(?:[^'\\\n]|\\.)*'|"(?:[^"\\\n]|\\.)*")"""
SHOWN_CALL = re.compile(r"\b(?:Text|SelectableText|TextSpan\(\s*text:|Tooltip\(\s*message:)\s*\(?\s*" + STR)
SHOWN_ARG = re.compile(r"\b(labelText|hintText|helperText|errorText|tooltip|title|subtitle|label|message|"
                       r"semanticLabel|buttonText|actionLabel|emptyText|placeholder|header|description)\s*:\s*" + STR)
RAW_VAR = re.compile(r"\bText\(\s*([a-z_]\w*(?:\.\w+|\[[^\]]+\])*\.(?:name|title|label|description|subtitle|"
                     r"category|type|status|message))\s*[,)]")
SKIP_FILE = re.compile(r"(_test|\.g|\.freezed)\.dart$|/l10n/|firebase_options")


def english(text):
    body = re.sub(r"\$\{[^{}]*\}|\$\w+", "", text[1:-1])
    return len(re.findall("[A-Za-z]", body)) >= 3 and re.search(r"[A-Za-z]{2,}", body) and not re.fullmatch(
        r"[\w./:-]*\.(png|jpg|json|svg|webp)|https?://\S*|[a-z_]+(\.[a-z_]+)+|[A-Z0-9_]{1,4}|#?[0-9A-Fa-f]{6,8}", body.strip())


def wrapped(line, start):
    before = line[:start]
    return re.search(r"\btr\w*\(\s*$|\bcountryName\(\s*$|tr\(\s*['\"]", before[-20:]) is not None


found = {'A': defaultdict(list), 'B': defaultdict(list), 'B2': defaultdict(list), 'C': defaultdict(list)}
for text, file in code_strings().items():
    if text.strip().lower() not in known:
        found['A'][file].append(text)
for path in sorted((ROOT / 'lib').rglob('*.dart')):
    rel = path.relative_to(ROOT).as_posix()
    if SKIP_FILE.search(rel):
        continue
    for no, line in enumerate(path.read_text(encoding='utf-8').splitlines(), 1):
        code = line.split('//')[0] if not re.search(r"['\"][^'\"]*//", line) else line
        if code.lstrip().startswith(('import ', 'export ', 'part ', 'debugPrint', 'print(', 'log(', 'throw ')):
            continue
        for m in list(SHOWN_CALL.finditer(code)) + list(SHOWN_ARG.finditer(code)):
            s = m.group(m.lastindex)
            if english(s) and not wrapped(code, m.start(m.lastindex)) and 'tr(' not in code[max(0, m.start() - 4):m.start()]:
                # In the catalog: probably translated where it's displayed (tr(variable)).
                text = re.sub(r"\$\{[^{}]*\}|\$[A-Za-z_]\w*", "{0}", s[1:-1]).replace("\\'", "'").replace('\\n', '\n')
                bucket = 'B2' if text.strip().lower() in known else 'B'
                found[bucket][rel].append(f"{no}: {s[:90]}")
        for m in RAW_VAR.finditer(code):
            found['C'][rel].append(f"{no}: Text({m.group(1)})")

titles = {'A': "tr('...') with no translation", 'B': 'English literals without tr() and not in the catalog',
          'B2': 'English literals without tr() but in the catalog (check the display site)',
          'C': 'Raw variables shown (check: data names vs UI text)'}
out = [f'# Untranslated UI text ({lang})', '', 'Generated by scan_untranslated.py; do not edit.', '']
for key in ('A', 'B', 'C', 'B2'):
    total = sum(len(v) for v in found[key].values())
    out += [f'## {key}. {titles[key]} — {total} in {len(found[key])} files', '']
    for file, items in sorted(found[key].items(), key=lambda kv: -len(kv[1])):
        out.append(f'### {file} ({len(items)})')
        out += [f'- `{i}`' for i in items]
        out.append('')
    print(f'{key}: {total} in {len(found[key])} files')
(Path(__file__).parent / 'untranslated_report.md').write_text('\n'.join(out), encoding='utf-8')

"""Idempotent statistics migration. --check validates without writing."""
import argparse
import json
from pathlib import Path
from statistics_schema import DATASETS, decode_statistics, encode_statistics, validate_statistics

ROOT = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    count = 0
    for name in DATASETS:
        path = ROOT / 'assets' / f'{name}.json'
        current = json.loads(path.read_text(encoding='utf-8-sig'))
        canonical = encode_statistics(name, current)
        validate_statistics(canonical)
        if canonical['dataset_id'] != name:
            raise ValueError(f'{name}: dataset id mismatch')
        # A second encoding checks record shape without resetting real metadata.
        rebuilt = encode_statistics(name, decode_statistics(canonical))
        if rebuilt['legacy_layout'] != canonical['legacy_layout']:
            raise ValueError(f'{name}: invalid layout')
        if [t['id'] for t in rebuilt['tables']] != [t['id'] for t in canonical['tables']]:
            raise ValueError(f'{name}: duplicate table identifiers')
        for table, expected in zip(canonical['tables'], rebuilt['tables']):
            if table['dimensions'] != expected['dimensions'] or [m['id'] for m in table['metrics']] != [m['id'] for m in expected['metrics']]:
                raise ValueError(f'{name}: invalid dimension/metric definitions')
            if table['records'] != expected['records']:
                raise ValueError(f'{name}: overlapping dimensions/values')
        if args.check:
            if current != canonical:
                raise ValueError(f'{name}: migration required')
        else:
            if decode_statistics(canonical) != decode_statistics(current):
                raise ValueError(f'{name}: migration changed values')
            path.write_text(json.dumps(canonical, ensure_ascii=False, indent=2) + '\n', encoding='utf8')
        count += sum(len(t['records']) for t in canonical['tables'])
    registry = ROOT / 'lib/services/statistics_assets.dart'
    registry_text = '// Generated by tool/migrate_statistics_schema.py.\nconst statisticsAssetPaths = <String>{\n'
    registry_text += ''.join(f"  'assets/{n}.json',\n" for n in DATASETS)
    registry_text += '};\n'
    if args.check:
        if registry.read_text(encoding='utf8') != registry_text:
            raise ValueError('Statistics asset registry is out of date')
    else:
        registry.write_text(registry_text, encoding='utf8')
    print(f'{len(DATASETS)} datasets, {count} records: ' + ('validated' if args.check else 'migrated losslessly'))


if __name__ == '__main__':
    main()
